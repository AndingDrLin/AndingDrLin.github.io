function optionLabels(options: string[]) {
  return options.map((option, index) => `${String.fromCharCode(65 + index)}. ${option}`).join("；");
}

function createQuestion(
  id: number,
  question: string,
  options: string[],
  correctText: string,
  explanation: string,
  tags: string[],
  difficulty: Difficulty
): LegacyQuestion {
  const rotated = rotate(options, id % options.length);
  return {
    id,
    question,
    options: rotated,
    answer: rotated.indexOf(correctText),
    explanation,
    tags,
    difficulty
  };
}

function expandSpec(spec: ConceptSpec, specIndex: number, startId: number): LegacyQuestion[] {
  const [trapA] = spec.traps;
  const [noteA, noteB, noteC] = spec.trapNotes;

  const explainCorrect = `正确项抓住了“${spec.title}”的关键：${spec.reason} 其他选项分别错误在：${noteA}；${noteB}；${noteC}`;
  const falseOptions = [spec.correct, spec.scopeCorrect, spec.applicationCorrect, trapA];
  const explainFalse = `本题问“错误说法”。“${trapA}”错误，原因是：${noteA}。其余选项均符合 PDF 中关于“${spec.title}”的表述或适用范围。`;
  const appOptions = [spec.applicationCorrect, ...spec.applicationTraps];
  const explainApp = `应选“${spec.applicationCorrect}”。${spec.reason} 其他判断混淆了概念对象、边界条件或公式适用范围。`;
  const scopeOptions = [spec.scopeCorrect, ...spec.scopeTraps];
  const explainScope = `适用范围判断应选“${spec.scopeCorrect}”。${spec.reason} 其余选项属于过度推广或把不同场量的条件混用。`;

  return [
    createQuestion(
      startId,
      `关于“${spec.title}”，下列哪项表述正确？`,
      [spec.correct, ...spec.traps],
      spec.correct,
      `${explainCorrect} 选项对照：${optionLabels([spec.correct, ...spec.traps])}。`,
      spec.tags,
      spec.difficulty
    ),
    createQuestion(
      startId + 1,
      `关于“${spec.title}”，下列哪项说法错误？`,
      falseOptions,
      trapA,
      `${explainFalse} 选项对照：${optionLabels(falseOptions)}。`,
      spec.tags,
      spec.difficulty
    ),
    createQuestion(
      startId + 2,
      spec.applicationQuestion,
      appOptions,
      spec.applicationCorrect,
      `${explainApp} 选项对照：${optionLabels(appOptions)}。`,
      spec.tags,
      spec.difficulty
    ),
    createQuestion(
      startId + 3,
      `关于“${spec.title}”的适用范围或边界理解，下列哪项正确？`,
      scopeOptions,
      spec.scopeCorrect,
      `${explainScope} 选项对照：${optionLabels(scopeOptions)}。`,
      spec.tags,
      spec.difficulty
    )
  ].map((question) => ({
    ...question,
    id: question.id + specIndex * 4
  }));
}

export const questions: LegacyQuestion[] = specs.flatMap((spec, index) => expandSpec(spec, index, 1));
